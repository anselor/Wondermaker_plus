"""Receipted Moonraker camera changes for the touchscreen installer.

The caller must stop the timelapse fixer before restoration and durably save
checkpoints. No service, printer G-code, or filesystem operations occur here.
request(method, path, params) returns the unwrapped Moonraker result.
"""
import copy
import uuid

WEBCAMS = '/server/webcams/list'
ITEM = '/server/webcams/item'
TIMELAPSE = '/machine/timelapse/settings'
SCREEN = dict(name='Touchscreen', service='iframe', location='printer',
              icon='mdiTelevision', enabled=True, aspect_ratio='5:3',
              target_fps=10, target_fps_idle=2, stream_url='/wmp-screen/',
              snapshot_url='/wmp-screen/snapshot.jpg', flip_horizontal=False,
              flip_vertical=False, rotation=0)


def _camera(request):
    cameras = request('GET', WEBCAMS, {})['webcams']
    if not isinstance(cameras, list):
        raise ValueError('Invalid webcam list')
    found = [cam for cam in cameras if cam['name'] == 'Touchscreen']
    if len(found) > 1:
        raise ValueError('Ambiguous Touchscreen webcam')
    return copy.deepcopy(found[0]) if found else None


def _selected(request):
    camera = request('GET', TIMELAPSE, {})['camera']
    if not isinstance(camera, str):
        raise ValueError('Invalid timelapse camera selection')
    return camera


def prepare(request, target='camera'):
    cameras = request('GET', WEBCAMS, {})['webcams']
    # Timelapse selection is optional; an unreadable selection is not
    # permission to overwrite it or change its boot-time fixer.
    try:
        timelapse = request('GET', TIMELAPSE, {})
        enabled, selected = timelapse['enabled'], timelapse['camera']
        if not isinstance(enabled, bool) or not isinstance(selected, str):
            raise ValueError('Invalid timelapse settings response')
    except (OSError, ValueError, KeyError, TypeError) as error:
        enabled, selected = None, None
        note = 'Timelapse settings unavailable; preserving selection and fixer: ' + str(error)
    else:
        note = 'Preserving the configured timelapse camera.'
    selected_valid = enabled is True and selected != 'Touchscreen' and sum(
        cam['name'] == selected for cam in cameras) == 1
    target_valid = target != 'Touchscreen' and sum(cam['name'] == target for cam in cameras) == 1
    manage_selection = enabled is True and not selected_valid and target_valid
    if enabled is False:
        note = 'Timelapse disabled; installing the screen bridge without camera selection.'
    elif enabled is True and not selected_valid and not target_valid:
        note = 'No unique print camera; installing the screen bridge without changing timelapse selection.'
    before = _camera(request)
    if before is not None and (before.get('source') != 'database' or not before.get('uid')):
        raise ValueError('Cannot replace a configuration-owned or unidentified webcam')
    after = dict(before or {}, **SCREEN)
    after['source'] = 'database'
    after['extra_data'] = dict(after.get('extra_data', {}), wmp_install_token=uuid.uuid4().hex)
    return dict(version=1, state='prepared', before=before, after=after,
                selected_before=selected, selected_after=target if manage_selection else selected,
                selection_managed=manage_selection,
                fixer_policy='preserve' if enabled is None else ('enable' if manage_selection else 'disable'),
                selection_note='' if manage_selection else note)


def _owned(current, receipt):
    if current is None:
        return False
    expected = receipt['after']
    # New webcam UUIDs are generated by Moonraker. The checkpointed ownership
    # token lets readback identify a successful POST whose reply was lost.
    if 'uid' not in expected:
        current = dict(current)
        if not current.pop('uid', None):
            return False
    return current == expected


def _save(receipt, checkpoint, state):
    receipt['state'] = state
    checkpoint(copy.deepcopy(receipt))


def apply(request, receipt, checkpoint):
    if receipt.get('version') != 1 or receipt.get('state') != 'prepared':
        raise ValueError('Camera changes require a prepared receipt')
    managed = receipt.get('selection_managed', True)
    if _camera(request) != receipt['before'] or (managed and _selected(request) != receipt['selected_before']):
        raise ValueError('Camera settings changed since review')
    _save(receipt, checkpoint, 'publishing-camera')
    payload = {k: v for k, v in receipt['after'].items() if k != 'source'}
    request('POST', ITEM, payload)
    current = _camera(request)
    if not _owned(current, receipt):
        raise ValueError('Webcam publication readback mismatch')
    receipt['after'] = current
    if not managed:
        _save(receipt, checkpoint, 'applied')
        return
    _save(receipt, checkpoint, 'publishing-selection')
    if _selected(request) != receipt['selected_before']:
        raise ValueError('Timelapse selection changed during installation')
    request('POST', TIMELAPSE, {'camera': receipt['selected_after']})
    if _selected(request) != receipt['selected_after']:
        raise ValueError('Timelapse selection readback mismatch')
    _save(receipt, checkpoint, 'applied')


def restore(request, receipt, checkpoint):
    if receipt.get('version') != 1 or receipt.get('state') not in (
            'prepared', 'publishing-camera', 'publishing-selection', 'applied',
            'restoring', 'restored'):
        raise ValueError('Invalid camera restoration receipt')
    managed = receipt.get('selection_managed', True)
    current = _camera(request)
    selected = _selected(request) if managed else receipt['selected_before']
    before = receipt['before']
    if receipt['state'] == 'restored':
        if current != before or selected != receipt['selected_before']:
            raise ValueError('Settings changed after completed camera restoration')
        return
    if current != before and not _owned(current, receipt):
        raise ValueError('Concurrent webcam edit; refusing restoration')
    if selected not in (receipt['selected_before'], receipt['selected_after']):
        raise ValueError('Concurrent timelapse selection; refusing restoration')
    _save(receipt, checkpoint, 'restoring')
    if current != before:
        if _camera(request) != current:
            raise ValueError('Webcam changed during restoration')
        if before is None:
            request('DELETE', ITEM, {'uid': current['uid']})
        else:
            request('POST', ITEM, {k: v for k, v in before.items() if k != 'source'})
        if _camera(request) != before:
            raise ValueError('Webcam restoration readback mismatch')
    current_selection = _selected(request) if managed else receipt['selected_before']
    if current_selection != receipt['selected_before']:
        if current_selection != receipt['selected_after']:
            raise ValueError('Timelapse selection changed during restoration')
        request('POST', TIMELAPSE, {'camera': receipt['selected_before']})
    if _camera(request) != before or (managed and _selected(request) != receipt['selected_before']):
        raise ValueError('Camera restoration readback mismatch')
    _save(receipt, checkpoint, 'restored')
