#!/usr/bin/env python3
"""Conservative offline macro inventory. Does not execute Jinja or contact a printer."""
import hashlib,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'docs/command-audit'
RULES={
 'homing':r'^(G28|ECHELON_STEPPER_HOMING|_WMP_COUPLING_STROKE|_WMP_FAILED_PICKUP_CLEANUP)$',
 'axis-or-extruder-motion':r'^(G0|G1|G2|G3|FORCE_MOVE|MANUAL_STEPPER|_WMP_COUPLING_STROKE|_WMP_FAILED_PICKUP_CLEANUP|SET_GCODE_OFFSET|RESTORE_GCODE_STATE)$',
 'heater':r'^(M104|M109|M140|M190|SET_HEATER_TEMPERATURE|TURN_OFF_HEATERS|TEMPERATURE_WAIT)$',
 'fan':r'^(M106|M107|SET_FAN_SPEED)$',
 'persistent-state':r'^(SAVE_VARIABLE|SAVE_CONFIG|SAVE_T_POSITON|_WMP_COUPLING_STROKE)$',
 'runtime-state':r'^(SET_GCODE_VARIABLE|SET_KINEMATIC_POSITION|G92|G90|G91|M82|M83|ACTIVATE_EXTRUDER|SET_STEPPER_ENABLE|M84|M18|SET_VELOCITY_LIMIT|M220|M221)$',
 'job-or-service':r'^(SDCARD_RESET_FILE|SDCARD_PRINT_FILE|CLEAR_PAUSE|PAUSE|RESUME|CANCEL_PRINT|RESTART|FIRMWARE_RESTART|RUN_SHELL_COMMAND|UPDATE_DELAYED_GCODE)$',
 'probe-or-calibration':r'^(PROBE|PROBE_CALIBRATE|BED_MESH_CALIBRATE|BED_MESH_CLEAR|Z_TILT_ADJUST|CALIBRATE_TOOL_OFFSETS|PID_CALIBRATE)$',
 'wait-or-barrier':r'^(M400|G4)$',
}
def scan(folder):
 rows=[]
 for path in sorted(folder.glob('*.cfg')):
  current=None
  for number,line in enumerate(path.read_text(errors='replace').splitlines(),1):
   m=re.match(r'^\[(gcode_macro|delayed_gcode|homing_override|idle_timeout)(?:\s+([^\]]+))?\]',line)
   if line.startswith('['):current=None
   if m:
    current={'name':m[2] or m[1],'kind':m[1],'file':str(path.relative_to(ROOT)),'line':number,'commands':[],'dynamic_lines':[],'rename_existing':None};rows.append(current);continue
   if current is None:continue
   t=line.strip()
   if re.match(r'^rename_existing\s*[:=]',t):current['rename_existing']=re.split(r'[:=]',t,maxsplit=1)[1].strip()
   if not t or t.startswith(('#',';')) or re.match(r'^[a-z_][a-z0-9_]*\s*[:=]',t):continue
   m=re.match(r'^([A-Za-z_][A-Za-z0-9_]*)(?:\s|$)',t)
   if m:current['commands'].append({'command':m[1].upper(),'line':number})
   elif '{' in t and not t.startswith(('{%','#')):current['dynamic_lines'].append(number)
 byname={}
 for row in rows:byname.setdefault(row['name'].upper(),[]).append(row)
 for row in rows:
  direct={c['command'] for c in row['commands']}
  row['calls']=sorted(direct & byname.keys())
  row['direct_effects']=sorted(k for k,pat in RULES.items() if any(re.match(pat,c) for c in direct))
  row['leaf_commands']=sorted(direct-byname.keys())
  row['callers']=sorted(set(r['name'] for r in rows if row['name'].upper() in {c['command'] for c in r['commands']}))
  row['possible_effects']=row['direct_effects'][:]
 for _ in range(len(rows)):
  changed=False
  for row in rows:
   effects=set(row['possible_effects'])
   for call in row['calls']:
    for target in byname[call]:effects.update(target['possible_effects'])
   if effects!=set(row['possible_effects']):row['possible_effects']=sorted(effects);changed=True
  if not changed:break
 return rows
OUT.mkdir(exist_ok=True)
allrows={label:scan(ROOT/'config'/label) for label in ('stock','live')}
inputs={str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for label in allrows for p in sorted((ROOT/'config'/label).glob('*.cfg'))}
(OUT/'macro-inventory.json').write_text(json.dumps({'scope':'All cfg definitions; potential static paths, not runtime traces or effective include order','inputs_sha256':inputs,'definitions':allrows},indent=2)+'\n')
for label,rows in allrows.items():
 lines=['# '+label+' macro effect inventory','',f'{len(rows)} definitions. Generated by `tools/audit_macro_effects.py`.','', 'Conditional branches are unioned. Duplicate definitions are retained; include precedence is not resolved. Dynamic Jinja calls and custom C/Python commands require manual review. Empty effects do not prove no side effects. Macro callers exclude the native screen client, slicer and external API callers.','', '| Definition | Source | Direct effects | Possible effects including static macro calls | Macro callers |','|---|---|---|---|---|']
 for r in rows:
  lines.append('| '+r['name']+' | ['+Path(r['file']).name+':'+str(r['line'])+'](../../'+r['file']+') | '+', '.join(r['direct_effects'])+' | '+', '.join(r['possible_effects'])+' | '+', '.join(r['callers'])+' |')
 (OUT/(label+'-inventory.md')).write_text('\n'.join(lines)+'\n')
print({k:len(v) for k,v in allrows.items()})
